// Prints the protected-route matrix (Markdown) from the EFFECTIVE router: it starts server.js with DUMP_ROUTES=1 against an empty temporary data
// directory (the server prints the keys of its real `routes` table and exits before listening), then classifies every key with
// platform-sso/route-policy.js. A source scan with a regular expression is only used as a cross-check and reported separately.
// Usage: node scripts/route-matrix.mjs > ROUTE-MATRIX.md
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { classifyRoute } from '../platform-sso/route-policy.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Keys of the effective router, in registration order. */
export function effectiveRoutes() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'route-dump-'));
  try {
    fs.writeFileSync(path.join(dir, 'secret'), crypto.randomBytes(32).toString('hex'), { mode: 0o600 });
    const run = spawnSync(process.execPath, ['server.js'], { cwd: root, encoding: 'utf8', timeout: 60_000,
      env: { PATH: process.env.PATH, SystemRoot: process.env.SystemRoot, DUMP_ROUTES: '1', DATA_DIR: dir, SECRET_FILE: path.join(dir, 'secret'), PORT: '0' } });
    const line = String(run.stdout).trim().split('\n').filter(Boolean).pop();
    const keys = JSON.parse(line || 'null');
    if (!Array.isArray(keys) || keys.length < 200) throw new Error(`could not dump the effective router: ${run.stderr || run.stdout}`);
    return keys;
  } finally { fs.rmSync(dir, { recursive: true, force: true }); }
}

/** Cross-check only: `METHOD /api/...` literals found in the sources (misses computed keys such as `POST ${PATH}`). */
export function scannedRoutes() {
  const found = new Set();
  const walk = dir => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      if (['node_modules', 'test', 'scripts'].includes(entry.name)) continue;
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) walk(full);
      else if (entry.name.endsWith('.js')) for (const m of fs.readFileSync(full, 'utf8').matchAll(/['"`](GET|POST|PUT|PATCH|DELETE) (\/api\/[A-Za-z0-9_/:.\-]*)['"`]/g)) found.add(`${m[1]} ${m[2]}`);
    }
  };
  walk(root);
  return found;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const keys = effectiveRoutes();
  const rows = keys.map(key => ({ key, ...classifyRoute(key) })).sort((a, b) => a.key.localeCompare(b.key));
  const scanned = scannedRoutes(), onlyEffective = keys.filter(key => !scanned.has(key)), onlyScanned = [...scanned].filter(key => !keys.includes(key));
  const label = { gated: 'capability-gated (enforced users)', staff: 'staff only (role guard in handler)', kiosk: 'kiosk token / PIN (memberGate / readKioskMember in handler)', identity: 'identity / passkey-only unless noted', member: 'member: interactive, closed by a suspension unless marked', public: 'public / pre-session', unclassified: 'UNCLASSIFIED' };
  console.log(`# Protected-route matrix (${rows.length} routes of the effective router)\n\nGenerated by \`api/scripts/route-matrix.mjs\`: the keys come from the \`routes\` table that \`server.js\` actually builds (\`DUMP_ROUTES=1\`), not from a source scan. \`sso\` = reachable with a Platform SSO session. Under enforcement, \`member\` routes are closed for a blocked (suspended / unlinked) account except \`withdrawal\` (delete/leave/block/unsubscribe/read) and \`read-ok\` (news, media, notifications reads).\n`);
  console.log(`Totals: ${Object.entries(rows.reduce((a, r) => (a[r.kind] = (a[r.kind] || 0) + 1, a), {})).map(([k, n]) => `${k} ${n}`).join(' · ')}\n`);
  console.log(`Cross-check with a source scan: ${scanned.size} literal keys; ${onlyEffective.length} effective routes are invisible to the scan (${onlyEffective.map(k => `\`${k}\``).join(', ') || 'none'}); ${onlyScanned.length} scanned strings are not routes (${onlyScanned.map(k => `\`${k}\``).join(', ') || 'none'}).\n`);
  for (const kind of ['gated', 'kiosk', 'member', 'identity', 'staff', 'public', 'unclassified']) {
    const list = rows.filter(r => r.kind === kind); if (!list.length) continue;
    console.log(`## ${label[kind]} — ${list.length}\n\n| Route | sso | Capabilities / suspended account |\n|---|---|---|`);
    for (const r of list) console.log(`| \`${r.key}\` | ${r.ssoAllowed ? 'yes' : 'no'} | ${(r.capabilities || []).join(', ') || (kind === 'member' ? (r.blockedOk ? 'withdrawal: stays open' : r.blockedReadOk ? 'read-ok when suspended (GET/HEAD)' : 'closed when suspended') : '—')} |`);
    console.log('');
  }
}
