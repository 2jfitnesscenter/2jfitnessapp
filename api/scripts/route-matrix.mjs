// Prints the protected-route matrix (Markdown) from the REAL route table: every `METHOD /api/...` key found in the API sources,
// classified by platform-sso/route-policy.js. Usage: node scripts/route-matrix.mjs > ROUTE-MATRIX.md
import fs from 'node:fs';
import path from 'node:path';
import { classifyRoute } from '../platform-sso/route-policy.js';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const found = new Set();
const walk = dir => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (['node_modules', 'test', 'scripts'].includes(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full);
    else if (entry.name.endsWith('.js')) for (const m of fs.readFileSync(full, 'utf8').matchAll(/['"`](GET|POST|PUT|PATCH|DELETE) (\/api\/[A-Za-z0-9_/:.\-]*)['"`]/g)) found.add(`${m[1]} ${m[2]}`);
  }
};
walk(root);
const rows = [...found].sort().map(key => ({ key, ...classifyRoute(key) }));
const label = { gated: 'capability-gated (enforced users)', staff: 'staff only (role guard in handler)', kiosk: 'kiosk token / PIN (memberGate in handler)', identity: 'identity / passkey-only unless noted', member: 'member, no capability', public: 'public / pre-session', unclassified: 'UNCLASSIFIED' };
console.log(`# Protected-route matrix (${rows.length} routes)\n\nGenerated by \`api/scripts/route-matrix.mjs\` from the real route table. \`sso\` = reachable with a Platform SSO session; sessions of kind sso are always strict.\n`);
console.log(`Totals: ${Object.entries(rows.reduce((a, r) => (a[r.kind] = (a[r.kind] || 0) + 1, a), {})).map(([k, n]) => `${k} ${n}`).join(' · ')}\n`);
for (const kind of ['gated', 'kiosk', 'member', 'identity', 'staff', 'public', 'unclassified']) {
  const list = rows.filter(r => r.kind === kind); if (!list.length) continue;
  console.log(`## ${label[kind]} — ${list.length}\n\n| Route | sso | Capabilities |\n|---|---|---|`);
  for (const r of list) console.log(`| \`${r.key}\` | ${r.ssoAllowed ? 'yes' : 'no'} | ${(r.capabilities || []).join(', ') || '—'} |`);
  console.log('');
}
