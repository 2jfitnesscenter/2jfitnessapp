// Keep both independent Docker build contexts self-contained, like sync-protocol.mjs.
import { readFileSync, writeFileSync } from 'node:fs'
const source = new URL('../frontend/src/lib/gym-profile-model.js', import.meta.url)
const target = new URL('../api/lib/gym-profiles.js', import.meta.url)
const expected = '// GENERATED by scripts/sync-gym-profiles.mjs — do not edit here.\n' + readFileSync(source, 'utf8').replace(/\r\n/g, '\n')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== expected) {
    console.error('Gym profile API copy is stale: run node scripts/sync-gym-profiles.mjs')
    process.exit(1)
  }
  console.log('Gym profile model in sync.')
} else {
  writeFileSync(target, expected)
  console.log('Generated API gym profile model.')
}
