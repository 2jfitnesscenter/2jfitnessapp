/* Exercise Library V2 — reproducible audit of the real exercise library.
 *
 *   node scripts/audit-exercise-library.mjs           # write docs/EXERCISE_LIBRARY_AUDIT.md
 *   node scripts/audit-exercise-library.mjs --check   # fail if the committed report is stale
 *
 * Deterministic (no dates, stable ordering): the same data always produces the same report.
 * It reports; it never fixes. Decisions live in frontend/src/lib/library/overrides.js.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'docs', 'EXERCISE_LIBRARY_AUDIT.md');
const imp = p => import(pathToFileURL(join(root, p)).href);
const { EXDB } = await imp('frontend/src/lib/exercises-data.js');
const es = (await imp('frontend/src/names/es.js')).default;
const { facetsOf, RECOMMENDED, norm, aliasIndexOf } = await imp('frontend/src/lib/library/core.js');
const { MOVEMENTS, EQUIPMENT, EQUIPMENT_OVERRIDE } = await imp('frontend/src/lib/protocol/movements.js');
const { DEPRECATED, REVIEWED_VARIANTS, MOVEMENT_OVERRIDE, ALIASES } = await imp('frontend/src/lib/library/overrides.js');
const { CATALOG } = await imp('frontend/src/lib/protocol/catalog.js');

const X = new Map(EXDB.map(e => [e.id, e]));
const F = new Map(EXDB.map(e => [e.id, facetsOf(e)]));
const L = [];
const p = s => L.push(s);
const count = (arr, key) => { const m = new Map(); for (const x of arr) { const k = key(x); m.set(k, (m.get(k) || 0) + 1); } return [...m].sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0]))); };
const pct = (n, d) => `${n} (${Math.round((n / d) * 1000) / 10} %)`;
const nm = id => `\`${id}\` ${X.get(id)?.n}`;
const T = EXDB.length;

p('# Exercise library audit');
p('');
p('Generated by `scripts/audit-exercise-library.mjs` from `frontend/src/lib/exercises-data.js`, `frontend/src/names/es.js`');
p('and the 2J layer (`frontend/src/lib/library/overrides.js`, `frontend/src/lib/protocol/movements.js`). Do not edit by hand.');
p('It reports; it never fixes. See `docs/EXERCISE_LIBRARY_V2.md` for the model and the decisions.');
p('');
p('## Totals');
p('');
p('| Metric | Value |');
p('|---|---|');
p(`| Exercises (dataset records) | ${T} |`);
p(`| Unique ids | ${new Set(EXDB.map(e => e.id)).size} |`);
p(`| Spanish name | ${pct(EXDB.filter(e => es[e.id]).length, T)} |`);
p(`| Image / GIF / instructions | ${EXDB.filter(e => e.img).length} / ${EXDB.filter(e => e.gif).length} / ${EXDB.filter(e => (e.st || []).length).length} |`);
p(`| Curated (protocol catalogue) | ${Object.keys(CATALOG).length} |`);
p(`| Recommended 2J | ${RECOMMENDED.size} |`);
p(`| With a canonical movement | ${pct(EXDB.filter(e => F.get(e.id).movement).length, T)} |`);
p(`| With a canonical equipment | ${pct(EXDB.filter(e => F.get(e.id).equipment).length, T)} |`);
p(`| Deprecated duplicates (kept, preferred id set) | ${Object.keys(DEPRECATED).length} |`);
p(`| Search/import aliases | ${Object.values(ALIASES).flat().length} on ${Object.keys(ALIASES).length} exercises |`);
p('');
p('## Dataset fields');
p('');
p('Body part (`bp`): ' + count(EXDB, e => e.bp).map(([k, n]) => `${k} ${n}`).join(' · '));
p('');
p('Target (`tg`): ' + count(EXDB, e => e.tg).map(([k, n]) => `${k} ${n}`).join(' · '));
p('');
p('| Dataset equipment (`eq`) | Records | Canonical |');
p('|---|---|---|');
for (const [k, n] of count(EXDB, e => e.eq)) p(`| ${k} | ${n} | ${EQUIPMENT.find(q => q.from.includes(k))?.id || '—'} |`);
p('');
p('## Canonical movements');
p('');
p('| Movement | All | Recommended 2J |');
p('|---|---|---|');
for (const m of MOVEMENTS) {
  const all = EXDB.filter(e => F.get(e.id).movement === m.id);
  p(`| ${m.id} | ${all.length} | ${all.filter(e => RECOMMENDED.has(e.id)).length} |`);
}
p(`| *(none — master only)* | ${EXDB.filter(e => !F.get(e.id).movement).length} | ${EXDB.filter(e => !F.get(e.id).movement && RECOMMENDED.has(e.id)).length} |`);
p('');
p('## Canonical equipment');
p('');
p(count(EXDB, e => F.get(e.id).equipment).map(([k, n]) => `${k} ${n}`).join(' · '));
p('');
p('Evidence-based overrides (the dataset `eq` is left as it is): ' + Object.entries(EQUIPMENT_OVERRIDE).map(([id, q]) => `${nm(id)} → ${q}`).join('; ') + '.');
p('');
p('Movement overrides: ' + Object.entries(MOVEMENT_OVERRIDE).map(([id, m]) => `${nm(id)} → ${m}`).join('; ') + '.');
p('');
p('## Duplicates');
p('');
p('Classes: **A** real duplicate (deprecated, preferred id) · **B** valid variant (kept, names made distinct) · **C** possible duplicate (kept, reported) · **D** distinct.');
p('');
p('### A — real duplicates (supported by matching dataset instructions/metadata or reviewed images)');
p('');
p('| Deprecated | Preferred |');
p('|---|---|');
for (const [d, pr] of Object.entries(DEPRECATED).sort()) p(`| ${nm(d)} | ${nm(pr)} |`);
p('');
p('### B — reviewed variants that shared a name');
p('');
for (const [a, b] of REVIEWED_VARIANTS) p(`- ${nm(a)} · ${nm(b)}`);
p('');
// C — automatic: same name once version/camera/model suffixes are removed, same movement and
// equipment, neither deprecated nor already reviewed.
const strip = s => norm(String(s).replace(/\bv\.? ?\d+\b/g, ' ').replace(/\((male|female)\)/g, ' ').replace(/\((back|side) pov\)/g, ' '));
const reviewed = new Set(REVIEWED_VARIANTS.map(pair => pair.slice().sort().join('|')));
const groups = new Map();
for (const e of EXDB) {
  if (DEPRECATED[e.id]) continue;
  const f = F.get(e.id);
  const k = `${strip(e.n)}|${f.equipment}`;
  groups.set(k, [...(groups.get(k) || []), e.id]);
}
const possible = [...groups.values()].filter(g => g.length > 1 && !reviewed.has(g.slice().sort().join('|')));
p(`### C — possible duplicates (${possible.length} groups; version "v. N", model or camera variants of one name)`);
p('');
p('Kept as they are: without a visual comparison they are not deprecated. Candidates for a future review.');
p('');
for (const g of possible) p('- ' + g.map(nm).join(' · '));
p('');
p('## Names');
p('');
const nonAscii = EXDB.filter(e => /[^\x20-\x7e]/.test(e.n));
p(`- Non-ASCII English names: ${nonAscii.length} (${nonAscii.map(e => nm(e.id)).join('; ') || 'none'}).`);
p(`- "v. N" suffixes: ${EXDB.filter(e => /\bv\. ?\d/.test(e.n)).length} · "(male)/(female)" model suffixes: ${EXDB.filter(e => /\((male|female)\)/.test(e.n)).length} (dataset labels, not renamed).`);
const liveNames = new Map();
for (const e of EXDB) if (!DEPRECATED[e.id]) { for (const n of [e.n, es[e.id]].filter(Boolean)) { const k = norm(n); liveNames.set(k, [...(liveNames.get(k) || []), e.id]); } }
p(`- Names shared by two live exercises (English or Spanish): ${[...liveNames.values()].filter(v => new Set(v).size > 1).length}.`);
p('');
p('## Metadata coherence');
p('');
const conditioning = EXDB.filter(e => e.bp === 'cardio' && F.get(e.id).kind !== 'cardio');
p(`- Filed as cardio without a cardio machine (read as conditioning): ${conditioning.length}.`);
const machineWords = EXDB.filter(e => e.eq === 'body weight' && /\b(lever|machine|smith|cable|sled|treadmill)\b/.test(e.n));
p(`- "body weight" with a machine word in the name: ${machineWords.length}${machineWords.length ? ' — ' + machineWords.map(e => nm(e.id)).join('; ') : ''}.`);
const lever = EXDB.filter(e => e.eq === 'leverage machine' && e.bp === 'cardio' && !EQUIPMENT_OVERRIDE[e.id]);
p(`- Cardio records still filed as "leverage machine" without an override: ${lever.length}${lever.length ? ' — ' + lever.map(e => nm(e.id)).join('; ') : ''}.`);
p('');
p('## Images');
p('');
const imgs = EXDB.map(e => e.img);
p(`- Every record has an image and a GIF: ${EXDB.every(e => e.img && e.gif) ? 'yes' : 'no'}; file names start with the record id: ${EXDB.every(e => e.img.startsWith(e.id)) ? 'yes' : 'no'}; unique: ${new Set(imgs).size === imgs.length ? 'yes' : 'no'}.`);
p('- Media are fetched from the upstream dataset and keep its own terms (see THIRD_PARTY_NOTICES.md); none is copied into this repository.');
p('');
p('## Imports');
p('');
const aliasIdx = aliasIndexOf();
p(`- Alias entries: ${aliasIdx.size}; each resolves to exactly one live exercise (the check fails otherwise).`);
p('- Import order: curated English alias → 2J alias → exact translated name → exact dataset name → word bag (only when exactly one candidate). A deprecated result is filed under its preferred id; ties are returned as candidates for the member to choose.');
p('');
p(`## Without a canonical movement (${EXDB.filter(e => !F.get(e.id).movement).length}, master library only)`);
p('');
p(EXDB.filter(e => !F.get(e.id).movement).map(e => nm(e.id)).join(' · '));
p('');

const md = L.join('\n');
if (process.argv.includes('--check')) {
  let cur = null;
  try { cur = readFileSync(out, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing = stale */ }
  if (cur !== md) { console.error('docs/EXERCISE_LIBRARY_AUDIT.md is out of date — run: node scripts/audit-exercise-library.mjs'); process.exit(1); }
  console.log(`docs/EXERCISE_LIBRARY_AUDIT.md in sync (${T} exercises, ${possible.length} possible-duplicate groups).`);
} else {
  writeFileSync(out, md);
  console.log(`Wrote ${out} — ${T} exercises, ${possible.length} possible-duplicate groups.`);
}
