// Keeps both independent Docker build contexts self-contained (same arrangement as
// sync-protocol.mjs and sync-gym-profiles.mjs): the pure overlay rules live in the frontend and the
// API gets a generated, byte-identical copy, so the server enforces exactly the rules the admin UI shows.
import { readFileSync, writeFileSync } from 'node:fs'
const source = new URL('../frontend/src/lib/library/overlay.js', import.meta.url)
const target = new URL('../api/lib/library-overlay.js', import.meta.url)
const expected = '// GENERATED by scripts/sync-library-overlay.mjs — do not edit here.\n' + readFileSync(source, 'utf8').replace(/\r\n/g, '\n')
if (process.argv.includes('--check')) {
  let have = null
  try { have = readFileSync(target, 'utf8').replace(/\r\n/g, '\n') } catch { /* missing = stale */ }
  if (have !== expected) {
    console.error('Library overlay API copy is stale: run node scripts/sync-library-overlay.mjs')
    process.exit(1)
  }
  console.log('Library overlay rules in sync.')
} else {
  writeFileSync(target, expected)
  console.log('Generated API library overlay rules.')
}
