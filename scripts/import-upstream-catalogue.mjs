/* Adds the exercises openGym (DuarteSantos8/openGym, AGPL-3.0, upstream commit 8fb98b16) has and
 * 2J does not, to the exercise dataset. Nothing that exists today is changed:
 *
 *   node scripts/import-upstream-catalogue.mjs <path-to-openGym-checkout>          # write
 *   node scripts/import-upstream-catalogue.mjs <path-to-openGym-checkout> --check  # fail if stale
 *
 * What is added: every upstream exercise that is not a drawing variant (`variantOf`) and whose id
 * is not already in our dataset. That is 4,308 exercises: 1,324 + 4,308 = 5,632, the number the
 * openGym v1.4.0 release announces. The 922 `variantOf` files are alternative drawings of an
 * exercise, not exercises; they arrive with the animations (a later step).
 *
 * Written files:
 *   frontend/src/lib/exercises-upstream.js   EXDB_UPSTREAM — same shape as EXDB, plus `ext`
 *   frontend/src/names/es-upstream.js        Spanish names of the added ids (ES_UPSTREAM)
 * and two one-line wrappers, so the existing records stay byte-identical:
 *   frontend/src/lib/exercises-data.js       EXDB = [...EXDB_BASE, ...EXDB_UPSTREAM]
 *   frontend/src/names/es.js                 default = { ...ES_BASE, ...ES_UPSTREAM }
 *
 * `ext` marks the added records. The Coach never receives them (api/coach/payload.js
 * librarySlice), so its prompts stay exactly as they are until the owner decides otherwise.
 * Images and animations are not imported: `img`/`gif` are null and the app shows its placeholder.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const SOURCE_COMMIT = '8fb98b16';
export const BASE_COUNT = 1324;
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = join(root, 'frontend', 'src', 'lib', 'exercises-data.js');
const NAMES = join(root, 'frontend', 'src', 'names', 'es.js');
const OUT_EX = join(root, 'frontend', 'src', 'lib', 'exercises-upstream.js');
const OUT_ES = join(root, 'frontend', 'src', 'names', 'es-upstream.js');
const HELD = join(root, 'docs', 'OPENGYM_CATALOGUE_HELD.json');

const sha = s => createHash('sha256').update(s).digest('hex');
// the same model label library/core.js drops from English display names (BASE_NAME)
const MODEL_LABEL = /\s*\((male|female)\)\s*$/i;
const STAMP = `// generated by scripts/import-upstream-catalogue.mjs from openGym ${SOURCE_COMMIT} (AGPL-3.0) — do not edit by hand\n`;

// `base` = the exercises we already have: { id, n, es } each. A candidate is taken only if neither its English nor
// its Spanish name is already used by a base exercise or by an earlier taken candidate. The rest are HELD, with the
// name they clash with, for an owner decision (openGym itself ships some duplicate names, e.g. "barbell hip thrust").
// `hasEquipment(record)` = the record's equipment string has a canonical id (protocol/movements.js). Equipment we do not
// model yet (suspension trainer, landmine, sandbag, macebell) is HELD: inventing a canonical id would change gym profiles.
export function buildAdditions(sourceDir, base, nameKey, hasEquipment = () => true) {
  const dir = join(sourceDir, 'catalogue', 'exercises');
  const esNames = JSON.parse(readFileSync(join(sourceDir, 'catalogue', 'i18n', 'es.json'), 'utf8'));
  const rows = readdirSync(dir).sort().map(f => JSON.parse(readFileSync(join(dir, f), 'utf8')));
  const baseIds = new Set(base.map(b => b.id));
  const taken = new Map();
  // an alias of a base exercise is a name too (checkLibrary: "alias … is the name of …"), so it blocks a candidate as well
  // The library layer drops a "(male)/(female)" label where the shorter name stays unique (library/core.js BASE_NAME), so
  // a base exercise's SHORT name is reserved too: an import with that name would make the original keep its label.
  for (const b of base) for (const k of [b.n, b.stripped, b.es, ...(b.aliases || [])].filter(Boolean).map(nameKey)) taken.set(k, b.id);
  const candidates = rows
    .filter(e => !e.variantOf && !baseIds.has(e.id))
    .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const added = [], held = [];
  for (const e of candidates) {
    const es = esNames[e.id]?.name || null;
    const keys = [e.name, e.name.replace(MODEL_LABEL, '').trim(), es].filter(Boolean).map(nameKey);
    const clash = keys.map(k => taken.get(k)).find(Boolean);
    // A decision already taken and tested by the owner's training-quality pass: no belt or pendulum squat machine is invented.
    if (/belt squat|pendulum squat/i.test(e.name)) { held.push({ id: e.id, n: e.name, es, reason: 'owner-decision', note: 'machine left out on purpose (library.test.js)' }); continue; }
    if (!hasEquipment({ id: e.id, eq: e.equipment })) { held.push({ id: e.id, n: e.name, es, reason: 'equipment', equipment: e.equipment }); continue; }
    if (clash) { held.push({ id: e.id, n: e.name, es, reason: 'name', clashesWith: clash }); continue; }
    for (const k of keys) taken.set(k, e.id);
    const sm = Array.isArray(e.secondaryMuscles) ? e.secondaryMuscles : [];
    added.push({ id: e.id, n: e.name, bp: e.bodyPart, eq: e.equipment, tg: e.target,
      mg: sm[0] ?? null, sm, st: e.instructions, img: null, gif: null, ext: 1, _es: es });
  }
  const names = Object.fromEntries(added.filter(e => e._es).map(e => [e.id, e._es]));
  for (const e of added) delete e._es;
  return { added, held, names };
}

// Idempotent wrapper edit: the base array keeps its exact bytes; only its declaration is renamed and the merge appended.
export function wrapBase(source, { declaration, baseName, importLine, mergeLine }) {
  if (source.includes(mergeLine)) return source;
  const head = `export const ${declaration}=[`;
  if (!source.includes(head)) throw new Error(`cannot find "${head}" in the dataset`);
  return importLine + source.replace(head, `const ${baseName}=[`).replace(/\n?$/, '\n') + mergeLine;
}

async function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const source = args.find(a => !a.startsWith('--'));
  if (!source) throw new Error('usage: node scripts/import-upstream-catalogue.mjs <openGym checkout> [--check]');
  const baseSrc = readFileSync(DATA, 'utf8');
  const baseIds = new Set([...baseSrc.matchAll(/\{"id":"(\d+)"/g)].map(m => m[1]));
  if (baseIds.size !== BASE_COUNT) throw new Error(`expected ${BASE_COUNT} base ids, found ${baseIds.size}`);
  // The exercises we already have, read from the dataset itself (ext-less records; the Spanish names of the same ids).
  const { EXDB } = await import(pathToFileURL(DATA).href);
  // the same normaliser checkLibrary uses (library/core.js re-exports it from overlay.js), so a clash here is a clash there
  const { norm: nameKey } = await import(pathToFileURL(join(root, 'frontend', 'src', 'lib', 'library', 'overlay.js')).href);
  const { default: ES } = await import(pathToFileURL(NAMES).href);
  const { ALIASES, NAME_OVERRIDE } = await import(pathToFileURL(join(root, 'frontend', 'src', 'lib', 'library', 'overrides.js')).href);
  const base = EXDB.filter(e => !e.ext).map(e => ({
    id: e.id, n: e.n, es: ES[e.id] || null, aliases: ALIASES[e.id] || [],
    stripped: NAME_OVERRIDE[e.id]?.n || e.n.replace(MODEL_LABEL, '').trim() || e.n,
  }));
  const { equipmentIdOf } = await import(pathToFileURL(join(root, 'frontend', 'src', 'lib', 'protocol', 'movements.js')).href);
  const { added, held, names } = buildAdditions(source, base, nameKey, r => !!equipmentIdOf(r));
  if (!check) writeFileSync(HELD, JSON.stringify({ source: SOURCE_COMMIT, held }, null, 2) + '\n');
  const exOut = STAMP + `export const EXDB_UPSTREAM=${JSON.stringify(added)};\n`;
  const esOut = STAMP + `export default ${JSON.stringify(names)};\n`;
  const exWrapped = wrapBase(baseSrc, {
    declaration: 'EXDB', baseName: 'EXDB_BASE',
    importLine: "import { EXDB_UPSTREAM } from './exercises-upstream.js'\n",
    mergeLine: 'export const EXDB = [...EXDB_BASE, ...EXDB_UPSTREAM]\n',
  });
  const esSrc = readFileSync(NAMES, 'utf8');
  const esWrapped = esSrc.includes('ES_UPSTREAM') ? esSrc
    : "import ES_UPSTREAM from './es-upstream.js'\n" + esSrc.replace('export default {', 'const ES_BASE = {').replace(/\n?$/, '\n') + 'export default { ...ES_BASE, ...ES_UPSTREAM }\n';
  if (check) {
    const stale = [[OUT_EX, exOut], [OUT_ES, esOut], [DATA, exWrapped], [NAMES, esWrapped]].filter(([p, want]) => !existsSync(p) || readFileSync(p, 'utf8') !== want).map(([p]) => p);
    if (stale.length) { console.error(`stale: ${stale.join(', ')} — run: node scripts/import-upstream-catalogue.mjs <checkout>`); process.exit(1); }
    console.log(`upstream additions in sync: ${added.length} exercises, ${Object.keys(names).length} Spanish names (sha256 ${sha(exOut).slice(0, 12)}).`);
    return;
  }
  writeFileSync(OUT_EX, exOut); writeFileSync(OUT_ES, esOut);
  writeFileSync(DATA, exWrapped); writeFileSync(NAMES, esWrapped);
  console.log(`Added ${added.length} exercises (${Object.keys(names).length} Spanish names) from openGym ${SOURCE_COMMIT}.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main().catch(e => { console.error(e.message); process.exit(1); });
